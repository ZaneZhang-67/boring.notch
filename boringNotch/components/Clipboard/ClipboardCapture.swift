import AppKit
import Foundation
import Security
import UniformTypeIdentifiers

struct CapturedClipboard: Sendable {
    let payload: ClipboardPayload
    let kind: ClipboardContentKind
    let title: String
    let subtitle: String?
    let searchText: String
    let thumbnailData: Data?
}

enum ClipboardCaptureResult: Sendable {
    case captured(CapturedClipboard)
    case ignored(ClipboardCaptureIgnoreReason)
}

enum ClipboardCaptureIgnoreReason: String, Sendable {
    case empty
    case concealed
    case transient
    case autogenerated
    case unsupported
}

enum ClipboardCaptureError: LocalizedError {
    case representationTooLarge(type: String, bytes: Int, limit: Int)
    case payloadTooLarge(bytes: Int, limit: Int)
    case bookmarkCreationFailed(path: String, reason: String)

    var errorDescription: String? {
        switch self {
        case .representationTooLarge(let type, let bytes, let limit):
            return "Clipboard representation \(type) is \(bytes) bytes, exceeding the \(limit)-byte safety limit."
        case .payloadTooLarge(let bytes, let limit):
            return "Clipboard payload is \(bytes) bytes, exceeding the \(limit)-byte safety limit."
        case .bookmarkCreationFailed(let path, let reason):
            return "Cannot persist access to clipboard file \(path): \(reason)"
        }
    }
}

@MainActor
struct ClipboardWriteResult: Sendable {
    let refreshedBookmarks: [ClipboardRefreshedBookmark]
}

enum ClipboardCapture {
    static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")
    private static var activeSecurityScopedURLs: [URL] = []
    private static var isRunningInAppSandbox: Bool {
        guard let task = SecTaskCreateFromSelf(nil),
              let value = SecTaskCopyValueForEntitlement(
                task,
                "com.apple.security.app-sandbox" as CFString,
                nil
              ) else { return false }
        return (value as? Bool) == true
    }

    private static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "com.agilebits.onepassword",
        "com.agilebits.onepassword.private",
        "com.1password.concealed"
    ]

    private static let transientTypes: Set<String> = [
        "org.nspasteboard.TransientType",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping"
    ]

    private static let autogeneratedTypes: Set<String> = [
        "org.nspasteboard.AutoGeneratedType"
    ]

    private static let metadataOnlyTypes: Set<String> = [
        sourceType.rawValue,
        "com.apple.pasteboard.source"
    ]

    static func read(
        from pasteboard: NSPasteboard,
        maximumRepresentationBytes: Int = 128 * 1024 * 1024,
        maximumPayloadBytes: Int = 256 * 1024 * 1024
    ) throws -> ClipboardCaptureResult {
        guard let pasteboardItems = pasteboard.pasteboardItems, !pasteboardItems.isEmpty else {
            return .ignored(.empty)
        }

        let allTypes = Set(pasteboardItems.flatMap { $0.types.map(\.rawValue) })
        if !allTypes.isDisjoint(with: concealedTypes) {
            return .ignored(.concealed)
        }
        if !allTypes.isDisjoint(with: transientTypes) {
            return .ignored(.transient)
        }
        if !allTypes.isDisjoint(with: autogeneratedTypes) {
            return .ignored(.autogenerated)
        }

        let sourceBundleIdentifier = pasteboardItems.lazy
            .compactMap { $0.string(forType: sourceType) }
            .first

        var payloadItems: [ClipboardPayloadItem] = []
        var totalBytes = 0

        for pasteboardItem in pasteboardItems {
            var representations: [ClipboardRepresentation] = []
            var seenTypes = Set<String>()

            for type in pasteboardItem.types {
                let identifier = type.rawValue
                guard !metadataOnlyTypes.contains(identifier), seenTypes.insert(identifier).inserted else {
                    continue
                }
                guard let data = pasteboardItem.data(forType: type) else { continue }
                guard data.count <= maximumRepresentationBytes else {
                    throw ClipboardCaptureError.representationTooLarge(
                        type: identifier,
                        bytes: data.count,
                        limit: maximumRepresentationBytes
                    )
                }
                totalBytes += data.count
                guard totalBytes <= maximumPayloadBytes else {
                    throw ClipboardCaptureError.payloadTooLarge(bytes: totalBytes, limit: maximumPayloadBytes)
                }
                representations.append(
                    ClipboardRepresentation(typeIdentifier: identifier, data: data)
                )
            }

            if let value = pasteboardItem.string(forType: .fileURL),
               let fileURL = URL(string: value), fileURL.isFileURL {
                do {
                    let bookmark = try fileURL.bookmarkData(
                        options: .withSecurityScope,
                        includingResourceValuesForKeys: nil,
                        relativeTo: nil
                    )
                    totalBytes += bookmark.count
                    guard totalBytes <= maximumPayloadBytes else {
                        throw ClipboardCaptureError.payloadTooLarge(bytes: totalBytes, limit: maximumPayloadBytes)
                    }
                    representations.append(
                        ClipboardRepresentation(
                            typeIdentifier: ClipboardRepresentation.securityScopedBookmarkType,
                            data: bookmark
                        )
                    )
                } catch let error as ClipboardCaptureError {
                    throw error
                } catch {
                    if isRunningInAppSandbox {
                        throw ClipboardCaptureError.bookmarkCreationFailed(
                            path: fileURL.path,
                            reason: error.localizedDescription
                        )
                    }
                    NSLog(
                        "[ClipboardHistory] Security bookmark unavailable for %@; preserving the file URL in this unsandboxed build: %@",
                        fileURL.path,
                        error.localizedDescription
                    )
                }
            }

            if !representations.isEmpty {
                payloadItems.append(ClipboardPayloadItem(representations: representations))
            }
        }

        guard !payloadItems.isEmpty else { return .ignored(.unsupported) }

        let payload = ClipboardPayload(
            items: payloadItems,
            sourceBundleIdentifier: sourceBundleIdentifier
        )
        let presentation = makePresentation(from: pasteboardItems, payload: payload)
        return .captured(
            CapturedClipboard(
                payload: payload,
                kind: presentation.kind,
                title: presentation.title,
                subtitle: presentation.subtitle,
                searchText: presentation.searchText,
                thumbnailData: presentation.thumbnailData
            )
        )
    }

    static func releaseSecurityScopedResources() {
        for url in activeSecurityScopedURLs {
            url.stopAccessingSecurityScopedResource()
        }
        activeSecurityScopedURLs = []
    }

    @discardableResult
    static func write(_ payload: ClipboardPayload, to pasteboard: NSPasteboard) throws -> ClipboardWriteResult {
        releaseSecurityScopedResources()

        var resolvedURLs: [URL] = []
        var refreshedBookmarks: [ClipboardRefreshedBookmark] = []
        var items: [NSPasteboardItem] = []
        do {
            for (itemIndex, payloadItem) in payload.items.enumerated() {
                if isRunningInAppSandbox {
                    let containsFileURL = payloadItem.representations.contains {
                        $0.typeIdentifier == NSPasteboard.PasteboardType.fileURL.rawValue
                    }
                    let containsBookmark = payloadItem.representations.contains {
                        $0.typeIdentifier == ClipboardRepresentation.securityScopedBookmarkType
                    }
                    if containsFileURL && !containsBookmark {
                        throw ClipboardWriteError.legacyFileAccessUnavailable
                    }
                }

                let pasteboardItem = NSPasteboardItem()
                var resolvedFileURL: URL?
                for representation in payloadItem.representations {
                    if representation.typeIdentifier == ClipboardRepresentation.securityScopedBookmarkType {
                        guard isRunningInAppSandbox else { continue }
                        var isStale = false
                        let url: URL
                        do {
                            url = try URL(
                                resolvingBookmarkData: representation.data,
                                options: [.withSecurityScope, .withoutUI],
                                relativeTo: nil,
                                bookmarkDataIsStale: &isStale
                            )
                        } catch {
                            throw ClipboardWriteError.bookmarkResolutionFailed(error.localizedDescription)
                        }
                        guard url.startAccessingSecurityScopedResource() else {
                            throw ClipboardWriteError.securityScopeDenied(url.path)
                        }
                        resolvedURLs.append(url)
                        if isStale {
                            do {
                                let refreshedData = try url.bookmarkData(
                                    options: .withSecurityScope,
                                    includingResourceValuesForKeys: nil,
                                    relativeTo: nil
                                )
                                refreshedBookmarks.append(
                                    ClipboardRefreshedBookmark(
                                        itemIndex: itemIndex,
                                        data: refreshedData
                                    )
                                )
                            } catch {
                                throw ClipboardWriteError.bookmarkResolutionFailed(
                                    "Could not refresh access for \(url.path): \(error.localizedDescription)"
                                )
                            }
                        }
                        resolvedFileURL = url
                        continue
                    }
                    pasteboardItem.setData(
                        representation.data,
                        forType: NSPasteboard.PasteboardType(representation.typeIdentifier)
                    )
                }
                if let resolvedFileURL {
                    pasteboardItem.setString(
                        resolvedFileURL.absoluteString,
                        forType: .fileURL
                    )
                }
                items.append(pasteboardItem)
            }
        } catch {
            for url in resolvedURLs {
                url.stopAccessingSecurityScopedResource()
            }
            throw error
        }

        let result = ClipboardWriteResult(refreshedBookmarks: refreshedBookmarks)
        guard !items.isEmpty else { return result }
        pasteboard.clearContents()
        guard pasteboard.writeObjects(items) else {
            for url in resolvedURLs {
                url.stopAccessingSecurityScopedResource()
            }
            throw ClipboardWriteError.writeRejected
        }
        activeSecurityScopedURLs = resolvedURLs
        return result
    }

    private static func makePresentation(
        from pasteboardItems: [NSPasteboardItem],
        payload: ClipboardPayload
    ) -> (kind: ClipboardContentKind, title: String, subtitle: String?, searchText: String, thumbnailData: Data?) {
        let fileURLs = pasteboardItems.compactMap { item -> URL? in
            guard let value = item.string(forType: .fileURL) else { return nil }
            return URL(string: value)
        }
        let plainTexts = pasteboardItems.compactMap { item in
            item.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines)
        }.filter { !$0.isEmpty }
        let webURLs = pasteboardItems.compactMap { item -> String? in
            guard let value = item.string(forType: .URL), !value.isEmpty else { return nil }
            return value
        }
        let typeIdentifiers = payload.items.flatMap { $0.representations.map(\.typeIdentifier) }
        let hasImage = typeIdentifiers.contains { identifier in
            UTType(identifier)?.conforms(to: .image) == true
        }
        let hasHTML = typeIdentifiers.contains(NSPasteboard.PasteboardType.html.rawValue)
        let hasRichText = typeIdentifiers.contains(NSPasteboard.PasteboardType.rtf.rawValue)
            || typeIdentifiers.contains(NSPasteboard.PasteboardType.rtfd.rawValue)

        let kind: ClipboardContentKind
        let title: String
        let subtitle: String?

        if !fileURLs.isEmpty {
            let names = fileURLs.map(\.lastPathComponent)
            let isSingleFolder = fileURLs.count == 1 && isDirectoryURL(fileURLs[0])
            kind = isSingleFolder ? .folder : .files
            if names.count == 1 {
                title = names[0]
            } else {
                let visibleNames = names.prefix(3).joined(separator: "、")
                title = names.count > 3 ? visibleNames + "…" : visibleNames
            }
            subtitle = isSingleFolder ? "Folder" : (names.count == 1 ? "File" : "\(names.count) items")
        } else if hasImage {
            kind = .image
            title = plainTexts.first.map { clipped($0, limit: 120) } ?? "Image"
            subtitle = imageDimensions(in: payload).map { "\($0.width) × \($0.height)" }
        } else if hasHTML {
            kind = .html
            let text = plainTexts.first ?? attributedText(from: pasteboardItems, type: .html) ?? "HTML content"
            title = clipped(text, limit: 120)
            subtitle = "HTML"
        } else if hasRichText {
            kind = .richText
            let text = plainTexts.first ?? attributedText(from: pasteboardItems, type: .rtf) ?? "Rich text"
            title = clipped(text, limit: 120)
            subtitle = "Rich text"
        } else if let url = webURLs.first {
            kind = .url
            title = clipped(plainTexts.first ?? url, limit: 120)
            subtitle = url
        } else if let text = plainTexts.first {
            kind = .text
            title = clipped(text, limit: 120)
            subtitle = text.contains("\n") ? clipped(text.replacingOccurrences(of: "\n", with: " "), limit: 180) : nil
        } else {
            kind = .other
            title = "Clipboard data"
            subtitle = Array(Set(typeIdentifiers)).sorted().prefix(3).joined(separator: ", ")
        }

        let searchableParts = plainTexts
            + fileURLs.flatMap { [$0.lastPathComponent, $0.path] }
            + webURLs
            + [title, subtitle ?? ""]
        let searchText = String(searchableParts.joined(separator: "\n").prefix(65_536))
        let thumbnailData = hasImage ? makeThumbnail(from: payload, maximumDimension: 160) : nil
        return (kind, title, subtitle, searchText, thumbnailData)
    }

    private static func isDirectoryURL(_ url: URL) -> Bool {
        if url.hasDirectoryPath { return true }
        return (try? url.resourceValues(forKeys: [.isDirectoryKey]).isDirectory) == true
    }

    private static func attributedText(
        from items: [NSPasteboardItem],
        type: NSPasteboard.PasteboardType
    ) -> String? {
        for item in items {
            guard let data = item.data(forType: type) else { continue }
            if type == .rtf, let attributed = NSAttributedString(rtf: data, documentAttributes: nil) {
                return attributed.string.trimmingCharacters(in: .whitespacesAndNewlines)
            }
            if type == .html,
               let attributed = try? NSAttributedString(
                    data: data,
                    options: [.documentType: NSAttributedString.DocumentType.html],
                    documentAttributes: nil
               ) {
                return attributed.string.trimmingCharacters(in: .whitespacesAndNewlines)
            }
        }
        return nil
    }

    private static func imageDimensions(in payload: ClipboardPayload) -> (width: Int, height: Int)? {
        guard let image = firstImage(in: payload) else { return nil }
        return (Int(image.size.width), Int(image.size.height))
    }

    private static func makeThumbnail(from payload: ClipboardPayload, maximumDimension: CGFloat) -> Data? {
        guard let image = firstImage(in: payload), image.size.width > 0, image.size.height > 0 else {
            return nil
        }
        let scale = min(1, maximumDimension / max(image.size.width, image.size.height))
        let targetSize = NSSize(width: image.size.width * scale, height: image.size.height * scale)
        let thumbnail = NSImage(size: targetSize)
        thumbnail.lockFocus()
        NSGraphicsContext.current?.imageInterpolation = .high
        image.draw(in: NSRect(origin: .zero, size: targetSize))
        thumbnail.unlockFocus()
        guard let tiff = thumbnail.tiffRepresentation,
              let bitmap = NSBitmapImageRep(data: tiff) else { return nil }
        return bitmap.representation(using: .png, properties: [:])
    }

    private static func firstImage(in payload: ClipboardPayload) -> NSImage? {
        for representation in payload.items.flatMap(\.representations) {
            if UTType(representation.typeIdentifier)?.conforms(to: .image) == true,
               let image = NSImage(data: representation.data) {
                return image
            }
        }
        return nil
    }

    private static func clipped(_ value: String, limit: Int) -> String {
        let normalized = value.replacingOccurrences(of: "\n", with: " ")
            .replacingOccurrences(of: "\t", with: " ")
            .trimmingCharacters(in: .whitespacesAndNewlines)
        guard normalized.count > limit else { return normalized }
        return String(normalized.prefix(limit)) + "…"
    }
}

enum ClipboardWriteError: LocalizedError {
    case writeRejected
    case legacyFileAccessUnavailable
    case bookmarkResolutionFailed(String)
    case securityScopeDenied(String)

    var errorDescription: String? {
        switch self {
        case .writeRejected:
            "macOS rejected the restored clipboard payload."
        case .legacyFileAccessUnavailable:
            "This older file entry has no persisted sandbox permission. Copy the file again to refresh access."
        case .bookmarkResolutionFailed(let reason):
            "Cannot resolve persisted clipboard file access: \(reason)"
        case .securityScopeDenied(let path):
            "macOS denied access to clipboard file \(path)."
        }
    }
}
